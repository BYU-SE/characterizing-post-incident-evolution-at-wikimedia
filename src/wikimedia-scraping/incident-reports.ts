export function cleanIRLink(str: string) {
  // replace colons in the URL
  if (str.includes(":")) {
    let first = str.slice(0, 6);
    let last = str.slice(6).replaceAll(":", "_");
    str = first + last;
  }

  // replace trailing slashes in the URL
  let slashStartIndex = "/wiki/Incidents/".length;
  if (str.lastIndexOf("/") > slashStartIndex) {
    let first = str.slice(0, slashStartIndex);
    let last = str.slice(slashStartIndex).replaceAll("/", "_");
    str = first + last;
  }

  return str;
}
