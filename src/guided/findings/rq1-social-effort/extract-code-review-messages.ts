import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";
import Papa from "papaparse";
import type { GerritCodeReview, GerritComment } from "../../../wikimedia-scraping/gerrit-types.js";

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

function shuffleArray<T>(array: T[]): T[] {
  const shuffled = [...array];
  for (let i = shuffled.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [shuffled[i], shuffled[j]] = [shuffled[j], shuffled[i]];
  }
  return shuffled;
}

function summarizeJenkinsMessage(message: string): string {
  // Parse vote from "Patch Set X: Verified+2" or "Patch Set X: -Verified"
  let vote = "";
  const voteMatch = message.match(/Patch Set \d+:\s*([-+]?\w+[+-]?\d*)/);
  if (voteMatch) {
    vote = voteMatch[1];
  }

  // Detect message type
  let messageType = "";
  if (message.includes("Main test build succeeded")) {
    messageType = "Main test build succeeded";
  } else if (message.includes("Main test build failed")) {
    messageType = "Main test build failed";
  } else if (message.includes("Gate pipeline")) {
    messageType = "Gate pipeline";
  } else if (message.includes("Starting gate")) {
    messageType = "Starting gate";
  } else if (message.includes("Merged")) {
    messageType = "Merged";
  } else if (message.includes("Build started")) {
    messageType = "Build started";
  } else if (message.includes("Build succeeded")) {
    messageType = "Build succeeded";
  } else if (message.includes("Build failed")) {
    messageType = "Build failed";
  } else {
    // Try to extract first meaningful line after Patch Set line
    const lines = message.split("\n").filter((l) => l.trim());
    for (const line of lines) {
      if (!line.startsWith("Patch Set") && !line.startsWith("- http")) {
        messageType = line.substring(0, 40);
        if (line.length > 40) messageType += "...";
        break;
      }
    }
  }

  // Count job lines (lines starting with "- http")
  const jobLines = message.split("\n").filter((l) => l.trim().startsWith("- http"));
  const jobCount = jobLines.length;

  // Build compact summary
  let summary = "";
  if (vote) {
    summary = vote;
    if (messageType) {
      summary += `: ${messageType}`;
    }
  } else if (messageType) {
    summary = messageType;
  } else {
    summary = "(automated message)";
  }

  if (jobCount > 0) {
    summary += ` (${jobCount} job${jobCount > 1 ? "s" : ""})`;
  }

  return summary;
}

async function extractCodeReviewMessages(numReviews: number = 10): Promise<void> {
  const gerritDir = path.join(__dirname, "../../../..", "data", "wikimedia-gerrit");

  // Read the CSV file to get valid code review IDs
  const csvPath = path.join(__dirname, "../../", "3-2-compare_code_reviews_pic.csv");
  const csvContent = fs.readFileSync(csvPath, "utf-8");
  const parseResult = Papa.parse(csvContent, { header: true });
  const validReviewIds = new Set<string>(
    parseResult.data.filter((row: any) => row.id).map((row: any) => row.id),
  );

  console.log(`Found ${validReviewIds.size} valid code review IDs in CSV`);

  // Get all JSON files that match the valid review IDs
  const allFiles = fs
    .readdirSync(gerritDir)
    .filter((f) => f.endsWith(".json"))
    .filter((f) => {
      const reviewId = f.replace(".json", "");
      return validReviewIds.has(reviewId);
    });

  console.log(`Found ${allFiles.length} matching JSON files`);

  // Shuffle files to process them in random order
  const shuffledFiles = shuffleArray(allFiles);

  const selectedReviews: GerritCodeReview[] = [];

  // Process files until we have enough code reviews with messages
  for (const file of shuffledFiles) {
    if (selectedReviews.length >= numReviews) {
      break;
    }

    const filePath = path.join(gerritDir, file);

    try {
      const content = fs.readFileSync(filePath, "utf-8");
      const data = JSON.parse(content) as GerritCodeReview;

      if (!data.messages || data.messages.length === 0) {
        continue;
      }

      // Filter out messages that are only from jenkins-bot or automated messages
      const humanMessages = data.messages.filter((msg) => {
        // Skip messages from jenkins-bot
        if (msg.author?.username === "jenkins-bot") {
          return false;
        }
        // Skip autogenerated messages
        if (
          msg.id &&
          (msg.id.includes("autogenerated") || (msg.message && msg.message.startsWith("Patch Set")))
        ) {
          return false;
        }
        return true;
      });

      if (humanMessages.length === 0) {
        continue;
      }

      selectedReviews.push(data);
      console.log(
        `Selected review ${selectedReviews.length}/${numReviews}: ${data._number} (${humanMessages.length} human messages)`,
      );
    } catch (error) {
      console.error(`Error processing ${file}:`, error);
    }
  }

  // Write to markdown file
  const outputPath = path.join(__dirname, "code-review-messages-sample.md");
  let markdown = `# Random Sample of Code Review Messages\n\n`;
  markdown += `**Generated:** ${new Date().toISOString()}\n\n`;
  markdown += `**Total Code Reviews:** ${selectedReviews.length}\n\n`;
  markdown += `---\n\n`;

  selectedReviews.forEach((review, reviewIndex) => {
    markdown += `## Review ${reviewIndex + 1}: ${review._number} - ${review.subject}\n\n`;
    markdown += `- **URL:** https://gerrit.wikimedia.org/r/c/${review._number}\n`;

    // Add author information
    if (review.owner) {
      const authorName = review.owner.display_name || review.owner.name;
      const authorUsername = review.owner.username;
      const authorEmail = review.owner.email;
      let authorStr = authorName;
      if (authorUsername) {
        authorStr += ` (@${authorUsername})`;
      }
      if (authorEmail) {
        authorStr += ` <${authorEmail}>`;
      }
      markdown += `- **Author:** ${authorStr}\n`;
    }

    markdown += `- **Project:** ${review.project}\n`;
    markdown += `- **Branch:** ${review.branch}\n`;
    markdown += `- **Status:** ${review.status}\n`;
    if (review.created) {
      markdown += `- **Created:** ${review.created}\n`;
    }
    if (review.updated) {
      markdown += `- **Updated:** ${review.updated}\n`;
    }
    markdown += `\n`;

    // Add commit message from current revision
    if (review.current_revision && review.revisions) {
      const currentRev = review.revisions[review.current_revision];
      if (currentRev?.commit?.message) {
        markdown += `**Commit Message:**\n\n`;
        markdown += `\`\`\`\n${currentRev.commit.message.trim()}\n\`\`\`\n\n`;
      }
    }

    const allMessages = review.messages;

    // Build a map of message ID -> inline comments
    const commentsByMessageId = new Map<string, { file: string; comment: GerritComment }[]>();
    if (review.comments) {
      for (const [filePath, comments] of Object.entries(review.comments)) {
        for (const comment of comments) {
          if (comment.change_message_id) {
            const existing = commentsByMessageId.get(comment.change_message_id) || [];
            existing.push({ file: filePath, comment });
            commentsByMessageId.set(comment.change_message_id, existing);
          }
        }
      }
    }

    // Count inline comments
    const inlineCommentCount = review.comments
      ? Object.values(review.comments).reduce((sum, comments) => sum + comments.length, 0)
      : 0;

    markdown += `**Messages:** ${allMessages.length}\n`;
    markdown += `**Inline Comments:** ${inlineCommentCount}\n\n`;

    // Output all messages with their associated inline comments
    allMessages.forEach((msg, msgIndex) => {
      const time = new Date(msg.date).toLocaleString();

      if (msg.author?.username === "jenkins-bot") {
        // Condensed one-liner format for jenkins-bot messages
        const summary = summarizeJenkinsMessage(msg.message);
        markdown += `**Message ${msgIndex + 1}:** 🤖 ${time} - ${summary}\n`;
      } else {
        // Full multi-line format for human messages
        const authorName = msg.author?.display_name || msg.author?.name || "Unknown";
        const authorUsername = msg.author?.username || "";
        const author = authorUsername ? `${authorName} (@${authorUsername})` : authorName;

        markdown += `**Message ${msgIndex + 1}: ${author}** - ${time}\n`;
        markdown += `${msg.message}\n\n`;

        // Print any inline comments attached to this message
        const attachedComments = commentsByMessageId.get(msg.id);
        if (attachedComments && attachedComments.length > 0) {
          markdown += `> **Inline Comments (${attachedComments.length}):**\n>\n`;
          for (const { file, comment } of attachedComments) {
            const commentAuthor = comment.author?.name || "Unknown";
            if (comment.line) {
              markdown += `> **${file}:${comment.line}** - ${commentAuthor}\n`;
            } else {
              markdown += `> **Patchset:** - ${commentAuthor}\n`;
            }
            markdown += `> ${comment.message.split("\n").join("\n> ")}\n>\n`;
          }
          markdown += `\n`;
        }
      }
    });

    markdown += `\n`;
  });

  fs.writeFileSync(outputPath, markdown, "utf-8");
  console.log(`\nWrote ${selectedReviews.length} code reviews to ${outputPath}`);

  // Print summary statistics
  const totalMessages = selectedReviews.reduce((sum, review) => sum + review.messages.length, 0);
  const totalInlineComments = selectedReviews.reduce((sum, review) => {
    if (!review.comments) return sum;
    return sum + Object.values(review.comments).reduce((s, comments) => s + comments.length, 0);
  }, 0);

  console.log(`Total messages: ${totalMessages}`);
  console.log(`Average messages per review: ${(totalMessages / selectedReviews.length).toFixed(1)}`);
  console.log(`Total inline comments: ${totalInlineComments}`);
  console.log(
    `Average inline comments per review: ${(totalInlineComments / selectedReviews.length).toFixed(1)}`,
  );
}

// Run the extraction
extractCodeReviewMessages(60).catch(console.error);
