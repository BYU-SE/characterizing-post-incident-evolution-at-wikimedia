export type FileExtensionCategory = keyof typeof FILE_EXTENSION_CATEGORIES;

/**
 * Creates a reverse lookup map from extension to category
 */
export const EXTENSION_TO_CATEGORY: Record<string, FileExtensionCategory> = {};

// Build reverse lookup
for (const [category, extensions] of Object.entries(FILE_EXTENSION_CATEGORIES)) {
  for (const ext of extensions) {
    EXTENSION_TO_CATEGORY[ext] = category as FileExtensionCategory;
  }
}

/**
 * Get the category for a file extension
 */
export function getExtensionCategory(extension: string): FileExtensionCategory | "other" {
  return EXTENSION_TO_CATEGORY[extension.toLowerCase()] || "other";
}

/**
 * Get all available categories
 */
export function getAllCategories(): FileExtensionCategory[] {
  return Object.keys(FILE_EXTENSION_CATEGORIES) as FileExtensionCategory[];
}
